卫星父引 = {
    "号卡": {
        "卫星表": "卫星_号卡属性",
        "父列": "号卡哈希",
        "父表": "枢纽_号卡",
        "期望父类": "枢纽_号卡",
    },
    "套餐": {
        "卫星表": "卫星_套餐属性",
        "父列": "套餐哈希",
        "父表": "枢纽_套餐",
        "期望父类": "枢纽_套餐",
    },
    "客户": {
        "卫星表": "卫星_客户属性",
        "父列": "客户哈希",
        "父表": "枢纽_客户",
        "期望父类": "枢纽_客户",
    },
    "订购": {
        "卫星表": "卫星_订购属性",
        "父列": "链接哈希",
        "父表": "链接_号卡套餐",
        "期望父类": "链接_号卡套餐",
    },
}

父表类 = (
    "枢纽_号卡",
    "枢纽_套餐",
    "枢纽_客户",
    "链接_号卡套餐",
    "链接_号卡客户",
)


def 父表有(conn, 表: str, 哈希: str) -> bool:
    if not 哈希:
        return False
    return conn.execute(f"SELECT 1 FROM {表} WHERE 哈希键=?", (哈希,)).fetchone() is not None


def 定位父类(conn, 哈希: str) -> str | None:
    """返回父哈希实际所属的父类；全表不可解返回 None。"""
    if not 哈希:
        return None
    for 表 in 父表类:
        if 父表有(conn, 表, 哈希):
            return 表
    return None


def 卫星父错挂(conn, 卫星类: str, 父哈希: str, 声明父类: str | None = None) -> dict | None:
    """只读校验一条卫星父引用；合法返回 None，否则返回错挂证据。"""
    引 = 卫星父引[卫星类]
    期望 = 引["期望父类"]
    if 声明父类 and 声明父类 != 期望:
        return {
            "卫星类": 卫星类,
            "父哈希": 父哈希 or "",
            "期望父类": 期望,
            "实际类": 声明父类,
            "原因": "类型交叉挂靠（声明父类与卫星类不符）",
        }
    if not 父哈希:
        return {
            "卫星类": 卫星类,
            "父哈希": "",
            "期望父类": 期望,
            "实际类": None,
            "原因": "父哈希缺失",
        }
    if 父表有(conn, 引["父表"], 父哈希):
        return None
    实际 = 定位父类(conn, 父哈希)
    return {
        "卫星类": 卫星类,
        "父哈希": 父哈希,
        "期望父类": 期望,
        "实际类": 实际,
        "原因": "类型交叉挂靠" if 实际 else "父哈希不存在",
    }
