def 原因码(原因: str | None) -> str:
    """把人类可读原因映射为稳定原因码；空原因也必须落兜底码。"""
    if not 原因:
        return 原因码_兜底
    原 = str(原因)
    for 前缀, 码 in 原因码表.items():
        if 原.startswith(前缀):
            return 码
    return 原因码_兜底


