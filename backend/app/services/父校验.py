class 错挂父异常(ValueError):
    """本批存在卫星错挂父 / 父不可解。整票失败闭，需整票回滚并同成败登册。"""

    def __init__(self, 明细: list[dict]):
        self.明细 = 明细
        super().__init__("；".join(
            f"{d['卫星类']}卫星父{d.get('父哈希') or '(空)'}→{d['原因']}" for d in 明细[:6]
        ))


def 父表有(conn, 表: str, 哈希: str) -> bool:
    if not 哈希:
        return False
    return conn.execute(f"SELECT 1 FROM {表} WHERE 哈希键=?", (哈希,)).fetchone() is not None


def 定位父类(conn, 哈希: str) -> str | None:
    """返回父哈希实际所属的父类；全表不可解返回 None。"""
    if not 哈希:
        return None
    for 表 in 父表类:
        if 父表有(conn, 表, 哈希):
            return 表
    return None


def 卫星父错挂(conn, 卫星类: str, 父哈希: str, 声明父类: str | None = None) -> dict | None:
    """只读校验一条卫星父引用；合法返回 None，否则返回错挂证据（含原因码）。"""
    引 = 卫星父引[卫星类]
    期望 = 引["期望父类"]
    if 声明父类 and 声明父类 != 期望:
        原因 = "类型交叉挂靠（声明父类与卫星类不符）"
        return {
            "卫星类": 卫星类,
            "父哈希": 父哈希 or "",
            "期望父类": 期望,
            "实际类": 声明父类,
            "原因": 原因,
            "原因码": 原因码(原因),
        }
    if not 父哈希:
        原因 = "父哈希缺失"
        return {
            "卫星类": 卫星类,
            "父哈希": "",
            "期望父类": 期望,
            "实际类": None,
            "原因": 原因,
            "原因码": 原因码(原因),
        }
    if 父表有(conn, 引["父表"], 父哈希):
        return None
    实际 = 定位父类(conn, 父哈希)
    原因 = "类型交叉挂靠" if 实际 else "父哈希不存在"
    return {
        "卫星类": 卫星类,
        "父哈希": 父哈希,
        "期望父类": 期望,
        "实际类": 实际,
        "原因": 原因,
        "原因码": 原因码(原因),
    }


def 现场父可解(conn, 卫星类: str, 父哈希: str, 声明父类: str | None = None) -> bool:
    """只读：现查该父是否可合法写出（父表命中且声明父类相符）。"""
    return 卫星父错挂(conn, 卫星类, 父哈希, 声明父类) is None


